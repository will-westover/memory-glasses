create view frame_segment as
select f.id as frame_id, s.id as segment_id, s.place_id, s.in_place_map
  from frame f join segment s on s.moment_id = f.moment_id and f.captured_at between s.start_at and s.end_at;

create table message (
    id              uuid primary key default gen_random_uuid(),
    conversation_id uuid not null references conversation (id) on delete cascade,
    created_at      timestamptz not null default clock_timestamp(),
    role            text not null,          -- 'user', 'assistant' or 'tool'
    content         jsonb not null          -- the message as it was sent or received
);

create index message_conversation on message (conversation_id, created_at);

insert into message (id, conversation_id, created_at, role, content)
select id, conversation_id, asked_at, 'user', jsonb_build_object('text', question) from turn;

insert into message (conversation_id, created_at, role, content)
select t.conversation_id, t.asked_at + make_interval(secs => coalesce(t.seconds, 0)) + interval '1 millisecond',
       'assistant',
       case when t.answer is null then jsonb_build_object('error', t.problem)
       else jsonb_build_object(
           'answer', jsonb_build_object(
               'answer', t.answer, 'found', t.found,
               'sources', coalesce((select jsonb_agg(s.fact_id order by s.position)
                                      from turn_source s where s.turn_id = t.id), '[]')),
           'facts', coalesce((select jsonb_agg(jsonb_build_object(
                                  'id', s.fact_id, 'kind', s.kind, 'at', s.at, 'moment_id', s.moment_id,
                                  'offset_seconds', s.offset_seconds, 'text', s.text, 'image_path', s.image_path)
                                  order by s.position)
                                from turn_source s where s.turn_id = t.id), '[]'))
       end
  from turn t;

alter table api_cost rename to model_call;

alter table model_call
    add column message_id uuid references message (id) on delete set null,   -- the chat message the call made
    add column request    jsonb,                                              -- kept for chat calls only
    add column response   jsonb;

update model_call c
   set message_id = m.id
  from turn t
  join message m on m.conversation_id = t.conversation_id and m.role = 'assistant'
       and m.created_at = t.asked_at + make_interval(secs => coalesce(t.seconds, 0)) + interval '1 millisecond'
 where c.step in ('agent', 'embed-question')
   and c.created_at between t.asked_at and t.asked_at + make_interval(secs => coalesce(t.seconds, 0) + 2);

