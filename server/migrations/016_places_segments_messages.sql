-- One table for where things happen, moments split into segments, raw chat messages, and clearer table names.
--   space and place become place: a name, an optional GPS circle and an optional phone map.
--   A moment is just a recording. Where it happened moves to its segments (a stretch of time at one place, or on
--   the move when place_id is null) and to location (GPS points over time).
--   turn and turn_source become message: each message as it was sent or received.

create table place_new (
    id         bigint generated by default as identity primary key,
    name       text,
    named      boolean not null default false,   -- the user chose the name, so models don't rename it
    lat        double precision,
    lon        double precision,
    radius_m   real,                              -- a location within this distance is at the place; null if unknown
    map_path   text,                              -- the phone's ARKit map, relative to the data folder
    updated_at timestamptz not null default now()
);

insert into place_new (id, name, named, lat, lon, map_path, updated_at)
select id, name, named, lat, lon, map_path, updated_at from space;

select setval(pg_get_serial_sequence('place_new', 'id'), greatest((select max(id) from place_new), 1));

insert into place_new (name, named, lat, lon, radius_m)
select name, true, lat, lon, radius_m from place;

create table segment (
    id           bigint generated always as identity primary key,
    moment_id    text not null references moment (id) on delete cascade,
    place_id     bigint references place_new (id) on delete set null,   -- null while on the move
    start_at     timestamptz not null,
    end_at       timestamptz not null,
    in_place_map boolean not null default false,                         -- positions are in the place's phone map
    summary      text
);

create index segment_moment on segment (moment_id, start_at);

insert into segment (moment_id, place_id, start_at, end_at, in_place_map)
select m.id, m.space_id, m.started_at,
       greatest(m.started_at + make_interval(secs => m.duration_seconds), coalesce(max(f.captured_at), m.started_at)),
       m.in_space_map
  from moment m left join frame f on f.moment_id = m.id
 group by m.id;

create table location (
    id         bigint generated always as identity primary key,
    moment_id  text not null references moment (id) on delete cascade,
    at         timestamptz not null,
    lat        double precision not null,
    lon        double precision not null,
    accuracy_m real
);

create index location_moment on location (moment_id, at);

insert into location (moment_id, at, lat, lon)
select id, started_at, lat, lon from moment where lat is not null and lon is not null;

